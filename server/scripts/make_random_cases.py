"""Write shared/rga-random.json: random sessions for both CRDTs to replay.

Generated file. Don't edit it by hand. Run from server/:
    uv run python -m scripts.make_random_cases
"""

import json
import random
from pathlib import Path

from app.rga import Doc, op_to_json

OUT = Path(__file__).resolve().parents[2] / "shared" / "rga-random.json"
SEEDS = range(50)
STEPS = 60


def make_case(seed: int) -> dict:
    rng = random.Random(seed)
    docs = [Doc(f"r{n}") for n in range(3)]
    log = []
    for _ in range(STEPS):
        doc = rng.choice(docs)
        roll = rng.random()
        if roll < 0.4 and log:
            doc.apply(rng.choice(log))
        elif roll < 0.8 or not doc.text():
            index = rng.randint(0, len(doc.text()))
            log.append(doc.local_insert(index, rng.choice("abcdef")))
        else:
            log.append(doc.local_delete(rng.randrange(len(doc.text()))))

    deliveries = log + rng.sample(log, len(log) // 4)  # some ops twice
    rng.shuffle(deliveries)

    reference = Doc("ref")
    for op in deliveries:
        reference.apply(op)
    return {
        "name": f"seed {seed}",
        "ops": [op_to_json(op) for op in deliveries],
        "text": reference.text(),
    }


if __name__ == "__main__":
    cases = [make_case(seed) for seed in SEEDS]
    data = {"about": "Generated by server/scripts/make_random_cases.py.", "cases": cases}
    OUT.write_text(json.dumps(data) + "\n")
    print(f"wrote {len(cases)} cases to {OUT}")